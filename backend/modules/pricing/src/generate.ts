import { and, asc, eq, gte, inArray, schema, withSystem, withVendor, type Tx } from '@oms/database';
import { resolveSettings } from '@oms/mod-vendors';
import type { Container, OpCtx } from '@oms/module-kit';
import { loadSubjects, pairKey, type Pair } from './proposal-context';
import { decide, moveBps, type PolicyView } from './proposal-domain';
import { applyProposal, insertProposal, openProposals } from './proposals';
import { SyncWork } from './service';

const L = schema.marketplaceListings;
const A = schema.marketplaceAccounts;
const POL = schema.pricingPolicies;
const PP = schema.pricingProposals;

/** more (variant, account) pairs than this are generated by a background job instead of inside the request */
export const SYNC_PAIR_LIMIT = 200;
/** a price the seller rejected is not proposed again for this long */
export const REJECT_COOLDOWN_DAYS = 7;

export interface GenerateInput { accountId?: string; variantIds?: string[]; policyId?: string; dryRun: boolean }
export interface GenerateItem {
  variantId: string; sku: string; accountId: string; status: 'proposed' | 'auto_applied' | 'unchanged' | 'skipped' | 'failed';
  currentPriceMinor: number; proposedPriceMinor: number | null; policyId: string | null; proposalId?: string; reason?: string;
}
export interface GenerateResult { dryRun: boolean; evaluated: number; proposed: number; autoApplied: number; unchanged: number; skipped: number; failed: number; items: GenerateItem[] }

/** the pairs worth evaluating: variants with an ACTIVE listing on an ACTIVE account */
export async function candidatePairs(tx: Tx, vendorId: string, f: { accountId?: string; variantIds?: string[] }, limit: number): Promise<Pair[]> {
  const rows = await tx.selectDistinct({ variantId: L.variantId, accountId: L.marketplaceAccountId }).from(L).innerJoin(A, and(eq(A.id, L.marketplaceAccountId), eq(A.vendorId, L.vendorId)))
    .where(and(eq(L.vendorId, vendorId), eq(L.status, 'active'), eq(A.status, 'active'), f.accountId ? eq(L.marketplaceAccountId, f.accountId) : undefined, f.variantIds?.length ? inArray(L.variantId, f.variantIds) : undefined))
    .orderBy(asc(L.marketplaceAccountId), asc(L.variantId)).limit(limit);
  return rows;
}

async function activePolicies(tx: Tx, vendorId: string, policyId?: string): Promise<Array<PolicyView & { accountId: string | null }>> {
  const rows = await tx.select().from(POL).where(and(eq(POL.vendorId, vendorId), eq(POL.status, 'active'), policyId ? eq(POL.id, policyId) : undefined)).orderBy(asc(POL.createdAt), asc(POL.id));
  return rows.map((p) => ({ id: p.id, name: p.name, accountId: p.accountId, strategy: p.strategy as PolicyView['strategy'], targetMarginMinBps: p.targetMarginMinBps, maxDiscountBps: p.maxDiscountBps, autoApproveUnderBps: p.autoApproveUnderBps, params: p.params }));
}

/**
 * Evaluate the active policies against each variant+account and open proposals. Per pair the first policy that proposes wins (policies
 * for one account come before policies for all accounts). Honest by construction: no competitor price means `automated_match` proposes
 * nothing; a price already proposed stays as it is; a price rejected recently is not proposed again; a move smaller than the policy's
 * `autoApproveUnderBps` is applied immediately (status `auto_applied`) through the pricing module, the rest waits for review.
 * `dryRun` evaluates and reports without writing.
 */
export async function generateProposals(tx: Tx, ctx: OpCtx, work: SyncWork, input: GenerateInput, pairs: Pair[], now = new Date()): Promise<GenerateResult> {
  const policies = await activePolicies(tx, ctx.vendorId, input.policyId);
  // workspace pricing rules from Settings: the price ending (9 / 0 / exact) and the MRP gate
  const [vendorRow] = await tx.select({ settings: schema.vendors.settings }).from(schema.vendors).where(eq(schema.vendors.id, ctx.vendorId));
  const rules = { ending: resolveSettings(vendorRow?.settings).pricing.priceEnding, mrpGate: resolveSettings(vendorRow?.settings).pricing.legalMetrologyMrpGate };
  const subjects = await loadSubjects(tx, ctx.vendorId, pairs, now);
  const open = await openProposals(tx, ctx.vendorId, [...new Set(pairs.map((p) => p.variantId))]);
  const since = new Date(now.getTime() - REJECT_COOLDOWN_DAYS * 86_400_000);
  const rejected = pairs.length ? await tx.select({ variantId: PP.variantId, accountId: PP.accountId, price: PP.proposedPriceMinor }).from(PP)
    .where(and(eq(PP.vendorId, ctx.vendorId), eq(PP.status, 'rejected'), gte(PP.decidedAt, since), inArray(PP.variantId, [...new Set(pairs.map((p) => p.variantId))]))) : [];
  const rejectedKeys = new Set(rejected.map((r) => `${r.variantId}:${r.accountId}:${r.price}`));
  const items: GenerateItem[] = [];
  const actor = ctx.actor;
  for (const pair of pairs) {
    const s = subjects.get(pairKey(pair));
    if (!s) continue;
    const base = { variantId: s.variantId, sku: s.sku, accountId: s.accountId, currentPriceMinor: s.subject.currentMinor };
    const applicable = [...policies.filter((p) => p.accountId === pair.accountId), ...policies.filter((p) => p.accountId === null)];
    if (applicable.length === 0) { items.push({ ...base, status: 'skipped', proposedPriceMinor: null, policyId: null, reason: 'no active policy applies' }); continue; }
    let reason = 'no policy proposes a change';
    let chosen: { policy: PolicyView; price: number; reasoning: string } | null = null;
    for (const policy of applicable) {
      const d = decide(policy, s.subject, rules);
      if (d.kind === 'propose') { chosen = { policy, price: d.proposedMinor, reasoning: d.reasoning }; break; }
      reason = `${policy.name}: ${d.reason}`;
    }
    if (!chosen) { items.push({ ...base, status: 'skipped', proposedPriceMinor: null, policyId: null, reason }); continue; }
    const common = { ...base, proposedPriceMinor: chosen.price, policyId: chosen.policy.id };
    if (rejectedKeys.has(`${pair.variantId}:${pair.accountId}:${chosen.price}`)) { items.push({ ...common, status: 'skipped', reason: 'this price was rejected recently' }); continue; }
    const existing = open.get(pairKey(pair));
    if (existing && existing.proposedPriceMinor === chosen.price) { items.push({ ...common, status: 'unchanged', proposalId: existing.id }); continue; }
    if (input.dryRun) { items.push({ ...common, status: 'proposed', reason: chosen.reasoning }); continue; }
    const row = await insertProposal(tx, ctx.vendorId, {
      variantId: pair.variantId, accountId: pair.accountId, strategy: chosen.policy.strategy, proposedPriceMinor: chosen.price, reasoning: chosen.reasoning, policyId: chosen.policy.id,
      elasticity: typeof chosen.policy.params.elasticity === 'number' ? chosen.policy.params.elasticity : undefined,
      expiresAt: typeof chosen.policy.params.expiresInDays === 'number' ? new Date(now.getTime() + chosen.policy.params.expiresInDays * 86_400_000) : undefined,
      actor: { type: actor.type, id: actor.id },
    }, s, now);
    const auto = chosen.policy.autoApproveUnderBps > 0 && Math.abs(moveBps(s.subject.currentMinor, chosen.price)) < chosen.policy.autoApproveUnderBps;
    if (!auto) { items.push({ ...common, status: 'proposed', proposalId: row.id }); continue; }
    const res = await applyProposal(tx, ctx, work, row, 'auto_applied', 'Applied automatically: the change is under the policy\'s auto-approve threshold');
    items.push(res.ok ? { ...common, status: 'auto_applied', proposalId: row.id } : { ...common, status: 'failed', proposalId: row.id, reason: res.message });
  }
  const n = (st: GenerateItem['status']) => items.filter((i) => i.status === st).length;
  return { dryRun: input.dryRun, evaluated: items.length, proposed: n('proposed'), autoApplied: n('auto_applied'), unchanged: n('unchanged'), skipped: n('skipped'), failed: n('failed'), items: items.slice(0, 500) };
}

/** run one vendor's generation in its own transaction (job / scheduler); price pushes go out after the commit */
export async function generateForVendor(c: Container, vendorId: string, input: Omit<GenerateInput, 'dryRun'>, maxPairs: number): Promise<GenerateResult> {
  const ctx: OpCtx = { c, vendorId, actor: { type: 'system', id: 'pricing-proposals' } };
  const work = new SyncWork();
  const res = await withVendor(c.database.db, vendorId, async (tx) => generateProposals(tx, ctx, work, { ...input, dryRun: false }, await candidatePairs(tx, vendorId, input, maxPairs)));
  await work.flush(c, vendorId);
  return res;
}

/** every vendor with an active policy gets a pass (the hourly scheduler tick) */
export async function generateAll(c: Container, maxPairs = 2_000): Promise<{ vendors: number; proposed: number; autoApplied: number }> {
  const vendors = await withSystem(c.database.db, (tx) => tx.selectDistinct({ id: POL.vendorId }).from(POL).where(eq(POL.status, 'active')));
  let proposed = 0;
  let autoApplied = 0;
  for (const v of vendors) {
    try {
      const r = await generateForVendor(c, v.id, {}, maxPairs);
      proposed += r.proposed;
      autoApplied += r.autoApplied;
    } catch (e) { c.logger.warn({ vendorId: v.id, err: (e as Error).message }, 'price proposal generation failed'); }
  }
  return { vendors: vendors.length, proposed, autoApplied };
}
